const derivedShare = (id: string, label: string, base: number, pct: number, baseLabel: string): Evidence => {
  const value = Math.round(base * (pct / 100))
  return {
    id,
    label: `${label} — approximate volume`,
    value,
    unit: 't',
    display: `~${value.toLocaleString()} t`,
    confidence: 'inferred',
    sourceId: 'derived',
    underlyingSourceIds: ['hm_asr_2025'],
    calculation: `${base.toLocaleString()} t (${baseLabel}) × ${pct}%`,
    confidenceNote: 'Approximate volume derived from reported material share — not reported H&M tonnage.',
  }
}

